from api_scanner import __version__
from api_scanner.exceptions import ExportError
from api_scanner.exporters.base import BaseExporter
from api_scanner.scanner.models import ScanResult


class HTMLExporter(BaseExporter):
    """Exports scan results to a standalone HTML report.

    Generates a modern, professional HTML report with embedded CSS.
    The report is completely self-contained with no external dependencies.
    Features card-based layout, color-coded risk badges, and responsive design.
    """

    def export(self, scan_result: ScanResult, output_path: str) -> str:
        """Export scan results to an HTML report file.

        Args:
            scan_result: The scan result data to export.
            output_path: The file path where the HTML should be written.

        Returns:
            The path to the created HTML file.

        Raises:
            ExportError: If the export operation fails.
        """
        try:
            file_path = Path(output_path)
            if not file_path.suffix:
                file_path = file_path.with_suffix(".html")

            html_content = self._build_report(scan_result)

            file_path.parent.mkdir(parents=True, exist_ok=True)
            file_path.write_text(html_content, encoding="utf-8")

            return str(file_path)

        except Exception as e:
            raise ExportError(f"Failed to export HTML: {e}") from e

    def _build_report(self, scan_result: ScanResult) -> str:
        """Build the complete HTML report string.

        Args:
            scan_result: The scan result to render.

        Returns:
            Complete HTML document as a string.
        """
        css = self._get_css()
        summary_section = self._build_summary(scan_result)
        endpoints_section = self._build_endpoints_table(scan_result)
        requests_section = self._build_requests_table(scan_result)
        storage_section = self._build_storage_section(scan_result)
        errors_section = self._build_errors_section(scan_result)

        export_time = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

        html = f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>API Scanner Report - {self._escape_html(scan_result.url)}</title>
    <style>
{css}
    </style>
</head>
<body>
    <div class="container">
        <header class="header">
            <h1>API Scanner Pro Report</h1>
            <p class="subtitle">Generated by API Scanner Pro v{__version__}</p>
            <p class="export-time">Report generated: {export_time}</p>
        </header>

        {summary_section}
        {endpoints_section}
        {requests_section}
        {storage_section}
        {errors_section}

        <footer class="footer">
            <p>API Scanner Pro v{__version__} | Report generated {export_time}</p>
        </footer>
    </div>
</body>
</html>"""
        return html

