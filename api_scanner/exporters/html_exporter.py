    def _build_summary(self, scan_result: ScanResult) -> str:
        """Build the summary section of the report.

        Args:
            scan_result: The scan result to summarize.

        Returns:
            HTML string for the summary section.
        """
        scan_time = scan_result.timestamp.strftime("%Y-%m-%d %H:%M:%S")
        endpoint_count = len(scan_result.api_endpoints)
        request_count = len(scan_result.requests)
        error_count = len(scan_result.errors)
        duration = f"{scan_result.scan_duration:.2f}s"

        return f"""
        <div class="card">
            <h2>Scan Summary</h2>
            <div class="summary-grid">
                <div class="summary-item">
                    <div class="label">Target URL</div>
                    <div class="value" style="font-size: 0.9rem; word-break: break-all;">{self._escape_html(scan_result.url)}</div>
                </div>
                <div class="summary-item">
                    <div class="label">Scan Time</div>
                    <div class="value" style="font-size: 1rem;">{scan_time}</div>
                </div>
                <div class="summary-item">
                    <div class="label">Duration</div>
                    <div class="value">{duration}</div>
                </div>
                <div class="summary-item">
                    <div class="label">API Endpoints</div>
                    <div class="value">{endpoint_count}</div>
                </div>
                <div class="summary-item">
                    <div class="label">Total Requests</div>
                    <div class="value">{request_count}</div>
                </div>
                <div class="summary-item">
                    <div class="label">Errors</div>
                    <div class="value" style="color: {'var(--danger)' if error_count > 0 else 'var(--success)'};">{error_count}</div>
                </div>
            </div>
        </div>"""

    def _build_endpoints_table(self, scan_result: ScanResult) -> str:
        """Build the API endpoints table section.

        Args:
            scan_result: The scan result containing endpoints.

        Returns:
            HTML string for the endpoints table.
        """
        if not scan_result.api_endpoints:
            return """
        <div class="card">
            <h2>API Endpoints</h2>
            <div class="empty-state">No API endpoints detected during scan.</div>
        </div>"""

        rows = ""
        for endpoint in scan_result.api_endpoints:
            method_class = f"method-{endpoint.method.lower()}"
            rows += f"""
                <tr>
                    <td class="url-cell">{self._escape_html(endpoint.url)}</td>
                    <td><span class="method-badge {method_class}">{endpoint.method}</span></td>
                    <td>{endpoint.timestamp.strftime("%H:%M:%S")}</td>
                </tr>"""

        return f"""
        <div class="card">
            <h2>API Endpoints ({len(scan_result.api_endpoints)} found)</h2>
            <table>
                <thead>
                    <tr>
                        <th>URL</th>
                        <th>Method</th>
                        <th>Time</th>
                    </tr>
                </thead>
                <tbody>{rows}
                </tbody>
            </table>
        </div>"""

    def _build_requests_table(self, scan_result: ScanResult) -> str:
        """Build the network requests table section (first 50).

        Args:
            scan_result: The scan result containing requests.

        Returns:
            HTML string for the requests table.
        """
        if not scan_result.requests:
            return """
        <div class="card">
            <h2>Network Requests</h2>
            <div class="empty-state">No network requests captured during scan.</div>
        </div>"""

        display_requests = scan_result.requests[:50]
        total_count = len(scan_result.requests)

        rows = ""
        for i, req in enumerate(display_requests):
            method_class = f"method-{req.method.lower()}"
            # Find matching response for status code
            status = ""
            content_type = ""
            for resp in scan_result.responses:
                if resp.url == req.url:
                    status_class = self._get_status_class(resp.status_code)
                    status = f'<span class="{status_class}">{resp.status_code}</span>'
                    content_type = resp.content_type
                    break

            rows += f"""
                <tr>
                    <td class="url-cell">{self._escape_html(req.url)}</td>
                    <td><span class="method-badge {method_class}">{req.method}</span></td>
                    <td>{status}</td>
                    <td>{self._escape_html(content_type)}</td>
                </tr>"""

        truncated_note = ""
        if total_count > 50:
            truncated_note = f'<p style="color: var(--text-muted); font-size: 0.875rem; margin-top: 1rem;">Showing 50 of {total_count} requests</p>'

        return f"""
        <div class="card">
            <h2>Network Requests ({total_count} total)</h2>
            <table>
                <thead>
                    <tr>
                        <th>URL</th>
                        <th>Method</th>
                        <th>Status</th>
                        <th>Content-Type</th>
                    </tr>
                </thead>
                <tbody>{rows}
                </tbody>
            </table>
            {truncated_note}
        </div>"""

    def _build_storage_section(self, scan_result: ScanResult) -> str:
        """Build the storage data section.

        Args:
            scan_result: The scan result containing storage data.

        Returns:
            HTML string for the storage section.
        """
        if not scan_result.storage_data:
            return """
        <div class="card">
            <h2>Storage Data</h2>
            <div class="empty-state">No storage data captured during scan.</div>
        </div>"""

        storage = scan_result.storage_data

        # Cookies table
        cookies_html = ""
        if storage.cookies:
            cookie_rows = ""
            for cookie in storage.cookies:
                secure_badge = '<span class="badge badge-safe">Yes</span>' if cookie.secure else '<span class="badge badge-high">No</span>'
                cookie_rows += f"""
                    <tr>
                        <td>{self._escape_html(cookie.name)}</td>
                        <td>{self._escape_html(cookie.domain)}</td>
                        <td class="url-cell">{self._escape_html(cookie.value[:50])}</td>
                        <td>{secure_badge}</td>
                    </tr>"""

            cookies_html = f"""
            <div class="storage-box" style="grid-column: 1 / -1;">
                <h3>Cookies ({len(storage.cookies)})</h3>
                <table>
                    <thead>
                        <tr>
                            <th>Name</th>
                            <th>Domain</th>
                            <th>Value</th>
                            <th>Secure</th>
                        </tr>
                    </thead>
                    <tbody>{cookie_rows}
                    </tbody>
                </table>
            </div>"""

        # Local storage
        local_storage_html = ""
        if storage.local_storage:
            items = ""
            for key, value in storage.local_storage.items():
                items += f"  {self._escape_html(key)}: {self._escape_html(str(value)[:100])}\n"
            local_storage_html = f"""
            <div class="storage-box">
                <h3>Local Storage ({len(storage.local_storage)} items)</h3>
                <pre>{items}</pre>
            </div>"""

        # Session storage
        session_storage_html = ""
        if storage.session_storage:
            items = ""
            for key, value in storage.session_storage.items():
                items += f"  {self._escape_html(key)}: {self._escape_html(str(value)[:100])}\n"
            session_storage_html = f"""
            <div class="storage-box">
                <h3>Session Storage ({len(storage.session_storage)} items)</h3>
                <pre>{items}</pre>
            </div>"""

        return f"""
        <div class="card">
            <h2>Storage Data</h2>
            <div class="storage-section">
                {local_storage_html}
                {session_storage_html}
                {cookies_html}
            </div>
        </div>"""

    def _build_errors_section(self, scan_result: ScanResult) -> str:
        """Build the errors section.

        Args:
            scan_result: The scan result containing errors.

        Returns:
            HTML string for the errors section.
        """
        if not scan_result.errors:
            return ""

        error_items = ""
        for error in scan_result.errors:
            error_items += f"<li>{self._escape_html(error)}</li>\n"

        return f"""
        <div class="card">
            <h2>Errors ({len(scan_result.errors)})</h2>
            <ul class="error-list">
                {error_items}
            </ul>
        </div>"""

    @staticmethod
    def _escape_html(text: str) -> str:
        """Escape HTML special characters.

        Args:
            text: Text to escape.

        Returns:
            HTML-safe string.
        """
        return (
            text.replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
            .replace('"', "&quot;")
            .replace("'", "&#x27;")
        )

    @staticmethod
    def _get_status_class(status_code: int) -> str:
        """Get CSS class for HTTP status code.

        Args:
            status_code: HTTP status code.

        Returns:
            CSS class name for the status code range.
        """
        if 200 <= status_code < 300:
            return "status-2xx"
        elif 300 <= status_code < 400:
            return "status-3xx"
        elif 400 <= status_code < 500:
            return "status-4xx"
        elif 500 <= status_code < 600:
            return "status-5xx"
        return ""
